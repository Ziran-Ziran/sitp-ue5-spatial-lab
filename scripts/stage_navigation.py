"""Stage this repository's native navigation bridge into a local experiment copy.

Does not build or launch UE. Never stages assets, edits a catalog or writes to a
shared source project. Targets are generated only when absent or byte-identical.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import re


ROOT = Path(__file__).resolve().parents[1]


def unlinked(path):
    for node in (path,*path.parents):
        if node.is_symlink() or (hasattr(os.path,'isjunction') and os.path.isjunction(node)):
            raise ValueError('linked experiment paths are not supported')


def digest(data):
    return hashlib.sha256(data).hexdigest()


def write_changed(path,data):
    if not path.exists() or path.read_bytes()!=data:
        path.write_bytes(data)


def stage(root, project, sources=None):
    root, project = Path(root).absolute(), Path(project).absolute()
    unlinked(project)
    relative = project.relative_to(root).as_posix()
    if not re.fullmatch(r'local/scenes/[a-z0-9-]+/workspace/UE5/[A-Za-z][A-Za-z0-9_]*\.uproject', relative):
        raise ValueError('project must be an independent local scene workspace')
    data = json.loads(project.read_text(encoding='utf-8-sig'))
    name = project.stem
    source_dir = project.parent / 'Source'
    config = project.parent / 'Config/DefaultEngine.ini'
    state_path = project.parent / '.sitp-navigation-stage.json'
    for path in (source_dir,config,state_path):
        unlinked(path)
    previous = json.loads(state_path.read_text(encoding='utf-8')) if state_path.exists() else {}
    targets = {}
    for suffix, kind in (('', 'Game'), ('Editor', 'Editor')):
        text = ('// Generated by SITP stage_navigation.py; source-only experiment target.\n'
                'using UnrealBuildTool;\n'
                f'public class {name}{suffix}Target : TargetRules\n{{\n'
                f'    public {name}{suffix}Target(TargetInfo Target) : base(Target)\n    {{\n'
                f'        Type = TargetType.{kind};\n'
                '        DefaultBuildSettings = BuildSettingsVersion.V7;\n'
                '        IncludeOrderVersion = EngineIncludeOrderVersion.Unreal5_8;\n'
                '        ExtraModuleNames.Add("SpatialLab");\n    }\n}\n')
        target = source_dir / f'{name}{suffix}.Target.cs'
        unlinked(target)
        if target.exists() and target.read_text(encoding='utf-8') != text:
            raise ValueError('existing target differs; refusing to overwrite user work')
        targets[target] = text
    sources = Path(sources) if sources else ROOT / 'ue5/tools/native/SpatialLab'
    unlinked(sources)
    if not (sources / 'SpatialLab.Build.cs').is_file():
        raise ValueError('missing native sources')
    files = []
    for directory,dirs,names in os.walk(sources,followlinks=False):
        for entry in (*dirs,*names):
            unlinked(Path(directory)/entry)
        files.extend(Path(directory)/name for name in names)
    modules = data.setdefault('Modules', [])
    ours = dict(Name='SpatialLab', Type='Runtime', LoadingPhase='Default')
    existing = [m for m in modules if m['Name'] == 'SpatialLab']
    if existing and existing != [ours]:
        raise ValueError('conflicting SpatialLab module declaration')
    planned = {target:text.encode('utf-8') for target,text in targets.items()}
    for source in files:
        if source.is_file() and source.suffix in ('.cs', '.cpp', '.h'):
            destination = source_dir / 'SpatialLab' / source.relative_to(sources)
            unlinked(destination)
            planned[destination] = source.read_bytes()
    for destination,content in planned.items():
        if destination.exists():
            if destination in targets and destination.read_text(encoding='utf-8') == targets[destination]:
                continue  # the earlier text preflight also accepts generated CRLF targets
            old = destination.read_bytes()
            relative_name = destination.relative_to(project.parent).as_posix()
            if old != content and previous.get('files',{}).get(relative_name) != digest(old):
                raise ValueError('local generated source differs; refusing to overwrite experiment work')
    text = config.read_text(encoding='utf-8-sig') if config.exists() else ''
    begin, end = '; BEGIN SITP navigation agent', '; END SITP navigation agent'
    old_block = None
    if begin in text:
        before, rest = text.split(begin,1)
        if end not in rest:
            raise ValueError('incomplete owned navigation configuration block')
        block,after = rest.split(end,1)
        old_block = begin+block+end+'\n'
        text = before+after
    agent_config = (
        begin + '\n'
        '[/Script/NavigationSystem.NavigationSystemV1]\n'
        '!SupportedAgents=ClearArray\n'
        '+SupportedAgents=(Name="SITPCapsule",AgentRadius=34.0,AgentHeight=176.0,NavDataClass="/Script/NavigationSystem.RecastNavMesh")\n'
        '[/Script/NavigationSystem.RecastNavMesh]\n'
        'AgentRadius=34.0\nAgentHeight=176.0\nAgentMaxSlope=45.0\n'
        'RuntimeGeneration=Static\n' + end + '\n')
    if old_block is not None and digest(old_block.encode()) != previous.get('config_block_sha256',digest(agent_config.encode())):
        raise ValueError('local navigation configuration changed; refusing overwrite')
    # No destination writes before the entire preflight passes.
    for destination,content in planned.items():
        destination.parent.mkdir(parents=True,exist_ok=True)
        write_changed(destination,content)
    if not existing:
        modules.append(ours)
    write_changed(project,(json.dumps(data,indent=2)+'\n').encode())
    config.parent.mkdir(exist_ok=True)
    write_changed(config,(text.rstrip()+'\n\n'+agent_config).encode())
    write_changed(state_path,(json.dumps(dict(schema_version=1,
        files={p.relative_to(project.parent).as_posix():digest(content) for p,content in planned.items()},
        config_block_sha256=digest(agent_config.encode())),indent=2)+'\n').encode())
    return dict(project=str(project), module='SpatialLab', staged=True, built=False)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--project', type=Path, required=True)
    args = parser.parse_args()
    print(json.dumps(stage(ROOT, args.project), indent=2))
